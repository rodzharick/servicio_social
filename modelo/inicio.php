        <h2 id="presentacion">Bienvenido a Servicio Social</h2>
        <p>
            Use el menú superior en el cual se encontrarán diferentes secciones donde cada una nos dará 
            un poco de información acerca del servicio social.
        </p>
        <p>
            El servicio social estudiantil es una herramienta de trabajo práctico que por ley se usa 
            para acercar a los estudiantes con la comunidad en trabajos de “Aprovechamiento del tiempo libre, 
            alfabetización, iniciativas ecológicas, eventos deportivos, la promoción y preservación de la salud, 
            la educación ciudadana, la organización de grupos juveniles y de preservación de factores socialmente 
            relevantes, la recreación dirigida, el fomento de actividades físicas, prácticas e intelectuales 
            y otros que la institución educativa considere pertinentes para el desempeño institucional”.
        </p>

        <h2 id="objetivos">Objetivos</h2>
        <h3>Objetivo general</h3>
        <p>
            Contribuir en la formación integral del estudiante Colrosarino, a través de su acercamiento con 
            la realidad de su entorno, consolidar la formación académica, desarrollar habilidades, competencias 
            y valores, que le faciliten la interacción con la sociedad.
        </p>

        <h3>Objetivos específicos</h3>
        <ul>
            <li>Vincular a los estudiantes en actividades de aprovechamiento del tiempo libre, alfabetización, ecológicas y deportivas.</li>
            <li>Desarrollar en los educandos compromisos sociales con la comunidad.</li>
            <li>Crear espacios de proyección a la comunidad.</li>
            <li>Fortalecer en los estudiantes los valores institucionales como responsabilidad, respeto, compromiso y solidaridad.</li>
            <li>Fomentar valores de solidaridad y compromiso en actividades formativas.</li>
        </ul>

        <h2 id="justificacion">Justificación</h2>
        <p>
            El proyecto de Servicio Social Estudiantil es obligatorio y debe ser realizado por todo estudiante 
            para poder cumplir con lo exigido por la ley para ser proclamado bachiller. 
            Este proyecto institucional busca comprometer a los jóvenes con el trabajo social y la ayuda a la comunidad educativa.
        </p>

        <h2 id="requisitos">Requisitos</h2>
        <ul>
            <li>Estar legalmente matriculado en la institución educativa y registrado en el Sistema de Matrículas (SIMAT).</li>
            <li>Estar cursando el grado 10 u 11.</li>
            <li>Inscribirse en los programas de Servicio Social aprobados por la institución y realizar los trámites administrativos.</li>
        </ul>

